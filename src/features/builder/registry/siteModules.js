function attachExplanation(mod) {
  const explanation = NODE_EXPLANATIONS[mod.id] || {
    whatItDoes: mod.summary || 'Operational step in OpsHub workflow.',
    whenToUse: `Use this when processing ${mod.name.toLowerCase()} in the workflow.`,
    example: `Standard operational execution of ${mod.name}.`,
    nextStep: mod.outputs === 0 ? 'Terminal step: No outgoing connection required.' : 'Connect to the next operational step or decision gate.',
    connectionRequirements: `${mod.inputs === 0 ? 'Starting trigger: 0 incoming connections needed' : `Requires ${mod.inputs} incoming connection`}; ${mod.outputs === 0 ? '0 outgoing connections (Terminal step)' : `${mod.outputs} outgoing connection(s) required`}.`,
    configurationNeeded: mod.supportedSettings && mod.supportedSettings.length > 0 ? mod.supportedSettings.map(s => s.label).join(', ') : 'No special configuration needed.',
  }
  return {
    ...mod,
    explanation,
  }
}

